//! The concept library: one entry per RL concept, unlocked when the player
//! reaches the tutorial step that teaches it (`docs/tutorials.md` §4).
//!
//! The same file generates `docs/rl-concepts.md`, so the documentation and
//! the game's text are one source.

use serde::{Deserialize, Serialize};

use crate::{Text, TutorialError};

pub const CONCEPTS_SCHEMA: u32 = 1;

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(rename = "Concepts", deny_unknown_fields)]
pub struct ConceptLibrary {
    pub schema: u32,
    pub concepts: Vec<ConceptDef>,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ConceptDef {
    pub id: String,
    pub title: String,
    /// The level whose tutorial teaches it.
    pub level: String,
    /// The tutorial step that explains it, counted from 0. Reaching it unlocks the entry.
    pub step: usize,
    /// One sentence, for the glossary.
    pub glossary: String,
    pub text: Text,
    /// Further reading: book chapters and papers.
    #[serde(default)]
    pub reading: Vec<String>,
}

impl ConceptLibrary {
    pub fn parse(source: &str) -> Result<Self, TutorialError> {
        let lib: Self = ron::Options::default()
            .with_default_extension(ron::extensions::Extensions::IMPLICIT_SOME)
            .from_str(source)
            .map_err(|e| {
                TutorialError(format!("line {}, column {}: {}", e.span.start.line, e.span.start.col, e.code))
            })?;
        lib.validate()?;
        Ok(lib)
    }

    pub fn validate(&self) -> Result<(), TutorialError> {
        if self.schema != CONCEPTS_SCHEMA {
            return Err(TutorialError(format!("schema: expected {CONCEPTS_SCHEMA}, found {}", self.schema)));
        }
        for (i, c) in self.concepts.iter().enumerate() {
            let err = |m: &str| Err(TutorialError(format!("concepts[{i}] \"{}\": {m}", c.id)));
            if c.id.trim().is_empty() || c.title.trim().is_empty() || c.glossary.trim().is_empty() {
                return err("id, title and glossary are required");
            }
            if c.text.story.trim().is_empty() || c.text.intuition.trim().is_empty() {
                return err("story and intuition text are required");
            }
            if self.concepts[..i].iter().any(|o| o.id == c.id) {
                return err("the id is used twice");
            }
        }
        Ok(())
    }

    pub fn get(&self, id: &str) -> Option<&ConceptDef> {
        self.concepts.iter().find(|c| c.id == id)
    }

    /// The library as a Markdown document. `level_title` names each level.
    pub fn to_markdown(&self, level_title: impl Fn(&str) -> String) -> String {
        let mut out = String::from(
            "# RL Concepts\n\n\
             The game's concept library, generated from `content/concepts.ron`. Do not edit this file: \
             edit the RON file and run `UPDATE_DOCS=1 cargo test -p rl-web concept_docs`.\n\n\
             Each concept is taught in one level's tutorial and unlocks in the game when the player reaches that step.\n",
        );
        let mut level = "";
        for c in &self.concepts {
            if c.level != level {
                level = &c.level;
                out.push_str(&format!("\n## {}\n", level_title(level)));
            }
            out.push_str(&format!("\n### {}\n\n*{}*\n\n", c.title, c.glossary));
            out.push_str(&format!("- **Story.** {}\n", c.text.story));
            out.push_str(&format!("- **Intuition.** {}\n", c.text.intuition));
            if let Some(math) = &c.text.math {
                out.push_str(&format!("- **Math.** {math}\n"));
            }
            if !c.reading.is_empty() {
                out.push_str(&format!("- **Further reading.** {}\n", c.reading.join("; ")));
            }
        }
        out
    }
}
